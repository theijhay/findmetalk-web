/**
 * Keep this app's API types in step with findmetalk-api (spec TR-8).
 *
 *   npm run contract:sync    copy the API's contract into contract/ and regenerate the types
 *   npm run contract:check   fail if the types or the copied contract are out of date
 *
 * The API publishes contract/openapi.json and contract/events.schema.json.
 * They are copied here so a build never depends on another checkout, and the
 * types in src/types/*.gen.ts are generated from the copy, never edited.
 *
 * The API contract is read from findmetalk-api's `development` branch in git
 * (API_REPO, default ../findmetalk-api; API_CONTRACT_REF, default
 * origin/development), so the result never depends on whatever branch the
 * sibling checkout happens to be on. API_CONTRACT_DIR reads a plain folder
 * instead. With no API repository at all, --check still verifies the types
 * against the copy.
 */

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CONTRACT_DIR = path.join(ROOT, "contract");
const API_REPO = path.resolve(process.env.API_REPO ?? path.join(ROOT, "..", "findmetalk-api"));
const API_CONTRACT_REF = process.env.API_CONTRACT_REF ?? "origin/development";
const API_CONTRACT_DIR = process.env.API_CONTRACT_DIR ? path.resolve(process.env.API_CONTRACT_DIR) : null;
const FILES = ["openapi.json", "events.schema.json"];

const BANNER = "// Generated by scripts/sync-contract.mjs from contract/. Do not edit.\n";

async function generate() {
  const openapi = astToString(await openapiTS(pathToFileURL(path.join(CONTRACT_DIR, "openapi.json"))));
  const eventsSchema = JSON.parse(readFileSync(path.join(CONTRACT_DIR, "events.schema.json"), "utf8"));
  const events = await compile(eventsSchema, "WebSocketEvents", {
    bannerComment: "",
    additionalProperties: false,
    strictIndexSignatures: true,
  });
  return {
    "src/types/api.gen.ts": BANNER + openapi,
    "src/types/events.gen.ts": BANNER + events,
  };
}

function read(file) {
  return existsSync(file) ? readFileSync(file, "utf8") : null;
}

/** The API's published contract, from a folder or from a git ref of the API repository. */
function readUpstream() {
  if (API_CONTRACT_DIR) {
    return {
      label: API_CONTRACT_DIR,
      files: Object.fromEntries(FILES.map((name) => [name, read(path.join(API_CONTRACT_DIR, name))])),
    };
  }
  if (!existsSync(path.join(API_REPO, ".git"))) return null;
  // Best effort: an offline machine still checks against the last fetched ref.
  try {
    execFileSync("git", ["-C", API_REPO, "fetch", "--quiet", "origin", "development"], { stdio: "ignore", timeout: 60_000 });
  } catch {}
  const show = (name) => {
    try {
      return execFileSync("git", ["-C", API_REPO, "show", `${API_CONTRACT_REF}:contract/${name}`], { encoding: "utf8" });
    } catch {
      return null;
    }
  };
  return { label: `findmetalk-api ${API_CONTRACT_REF}`, files: Object.fromEntries(FILES.map((name) => [name, show(name)])) };
}

async function main() {
  const check = process.argv.includes("--check");
  const problems = [];

  const upstream = readUpstream();
  if (upstream) {
    for (const name of FILES) {
      const local = path.join(CONTRACT_DIR, name);
      if (upstream.files[name] === null) {
        problems.push(`${name} is missing from ${upstream.label}`);
      } else if (upstream.files[name] !== read(local)) {
        if (check) problems.push(`contract/${name} differs from ${upstream.label}`);
        else writeFileSync(local, upstream.files[name]);
      }
    }
  } else if (!check) {
    console.error(`No API contract found (${API_REPO} at ${API_CONTRACT_REF}). Set API_REPO or API_CONTRACT_DIR.`);
    process.exit(1);
  } else {
    console.warn(`No API repository at ${API_REPO}; checking the types against contract/ only.`);
  }

  for (const [relative, content] of Object.entries(await generate())) {
    const file = path.join(ROOT, relative);
    if (read(file) === content) continue;
    if (check) problems.push(`${relative} is out of date`);
    else {
      writeFileSync(file, content);
      console.log(`wrote ${relative}`);
    }
  }

  if (problems.length) {
    console.error(`API contract drift:\n- ${problems.join("\n- ")}\nRun \`npm run contract:sync\` and commit the result.`);
    process.exit(1);
  }
}

await main();
