/**
 * Keep this app's API types in step with findmetalk-api (spec TR-8).
 *
 *   npm run contract:sync    copy the API's contract into contract/ and regenerate the types
 *   npm run contract:check   fail if the types or the copied contract are out of date
 *
 * The API publishes contract/openapi.json and contract/events.schema.json.
 * They are copied here so a build never depends on another checkout, and the
 * types in src/types/*.gen.ts are generated from the copy, never edited.
 *
 * The API contract is read from API_CONTRACT_DIR, or ../findmetalk-api/contract.
 * When neither exists, --check still verifies the types against the copy.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CONTRACT_DIR = path.join(ROOT, "contract");
const UPSTREAM_DIR = path.resolve(process.env.API_CONTRACT_DIR ?? path.join(ROOT, "..", "findmetalk-api", "contract"));
const FILES = ["openapi.json", "events.schema.json"];

const BANNER = "// Generated by scripts/sync-contract.mjs from contract/. Do not edit.\n";

async function generate() {
  const openapi = astToString(await openapiTS(pathToFileURL(path.join(CONTRACT_DIR, "openapi.json"))));
  const eventsSchema = JSON.parse(readFileSync(path.join(CONTRACT_DIR, "events.schema.json"), "utf8"));
  const events = await compile(eventsSchema, "WebSocketEvents", {
    bannerComment: "",
    additionalProperties: false,
    strictIndexSignatures: true,
  });
  return {
    "src/types/api.gen.ts": BANNER + openapi,
    "src/types/events.gen.ts": BANNER + events,
  };
}

function read(file) {
  return existsSync(file) ? readFileSync(file, "utf8") : null;
}

async function main() {
  const check = process.argv.includes("--check");
  const problems = [];

  if (existsSync(UPSTREAM_DIR)) {
    for (const name of FILES) {
      const upstream = read(path.join(UPSTREAM_DIR, name));
      const local = path.join(CONTRACT_DIR, name);
      if (upstream === null) {
        problems.push(`${path.join(UPSTREAM_DIR, name)} is missing`);
      } else if (upstream !== read(local)) {
        if (check) problems.push(`contract/${name} differs from ${path.join(UPSTREAM_DIR, name)}`);
        else writeFileSync(local, upstream);
      }
    }
  } else if (!check) {
    console.error(`No API contract at ${UPSTREAM_DIR}. Set API_CONTRACT_DIR.`);
    process.exit(1);
  } else {
    console.warn(`No API contract at ${UPSTREAM_DIR}; checking the types against contract/ only.`);
  }

  for (const [relative, content] of Object.entries(await generate())) {
    const file = path.join(ROOT, relative);
    if (read(file) === content) continue;
    if (check) problems.push(`${relative} is out of date`);
    else {
      writeFileSync(file, content);
      console.log(`wrote ${relative}`);
    }
  }

  if (problems.length) {
    console.error(`API contract drift:\n- ${problems.join("\n- ")}\nRun \`npm run contract:sync\` and commit the result.`);
    process.exit(1);
  }
}

await main();
